/* ---------------------------------------------------------------
   **הסריקה היא על חלון של שתי שורות, ולא על שורה — 16.9.2026.**

   `marketing/index.html` הוא רינדור של קובצי ה-md, שורה לשורה,
   וכל שורת מקור היא `<blockquote>` משלה. לכן משפט שנשבר בין
   שתי שורות נשבר גם בין שני אלמנטים, ורגקס על שורה בודדת אינו
   רואה אותו. זה קרה: ״שנבנו במיוחד עבור״ ישב בשורה 1988,
   ״תלמידים עם דיסלקציה״ בשורה 1989, והבדיקה עברה ירוק על טענה
   שנאסרה במפורש — באותו קובץ שבו היא **כן** נתפסה ב-md.

   הצירוף מדווח על השורה הראשונה מבין השתיים, ומדווח פעם אחת:
   התאמה שכבר נמצאה בשורה עצמה אינה מדווחת שוב מהחלון. */
for (const f of files) {
  const rel = path.relative(ROOT, f).replace(/\\/g, '/');
  const raw = fs.readFileSync(f, 'utf8').split('\n');
  /* HTML: התג עצמו אינו טקסט, והוא היה מפריד בין המילים בצירוף */
  const lines = /\.html$/.test(f) ? raw.map(l => l.replace(/<[^>]*>/g, ' ')) : raw;
  lines.forEach((l, i) => {
    const pair = i + 1 < lines.length ? l + ' ' + lines[i + 1] : null;
    for (const c of FORBIDDEN) {
      let m = l.match(c.re), src = l;
      if (m && quoted(l, m[0])) { m = null }
      if (!m && pair) {
        const pm = pair.match(c.re);
        /* רק צירוף אמיתי — התאמה שנכנסת כולה בשורה אחת כבר טופלה */
        if (pm && !lines[i + 1].match(c.re) && !quoted(pair, pm[0])) { m = pm; src = pair }
      }
      if (!m) continue;
      fail(`${rel}:${i + 1} — טענת ״${c.id}״: ${c.why}`);
      console.log(`    ${src.trim().replace(/\s+/g, ' ').slice(0, 92)}`);
      console.log(`    מותר במקומה: ${c.ok}`);
    }
  });
}
console.log(`${bad ? '✗' : '✓'} ${files.length} קבצים נסרקו, ${bad} טענות אסורות`);

/* ---------------------------------------------------------------
   והשתיים שהן מדידה: הפקודה רצה, והמספר שבטקסט מושווה אליה.

   זה מה שמונע מהרשימה עצמה להתיישן — בדיוק מה שקרה כאן.
   --------------------------------------------------------------- */
let stale = 0;
const facts = path.join(ROOT, 'marketing', 'facts.md');
if (fs.existsSync(facts)) {
  const txt = fs.readFileSync(facts, 'utf8');
  /* **רק השורה שטוענת, לא זו שמצטטת.** הסעיף ב-`facts.md` מסביר
     שהאיסור הישן התיישן, ולשם כך הוא מצטט את המספר המת — ובלי
     הסינון הזה הבדיקה הייתה נופלת על ההסבר עצמו. */
  const m = txt.split('\n')
    .filter(l => /clicks\.js/.test(l) && /\d+\s*מתוך\s*\d+/.test(l))
    .map(l => ({ l: l, hit: l.match(/(\d+)\s*מתוך\s*(\d+)/) }))
    .filter(x => x.hit && !quoted(x.l, x.hit[0]))
    .map(x => x.hit)[0];
  if (m) {
    /* 21.9.2026: `all.js` כבר הריץ את `clicks.js` (46 שניות, דפדפן)
       רגע לפני הבדיקה הזאת, והריצה השנייה כאן הכפילה אותו. עכשיו
       `clicks.js` משאיר סיכום ב-`.clicks-last.json`, וכאן משתמשים
       בו אם הוא מהשעה האחרונה. אין סיכום, או ישן — מריצים כמו
       קודם. המדידה נשארת מדידה; רק הכפילות הלכה. */
    let real = null;
    const LAST = path.join(__dirname, '.clicks-last.json');
    const MAX_AGE = 60 * 60 * 1000;
    try {
      const j = JSON.parse(fs.readFileSync(LAST, 'utf8'));
      if (j && Date.now() - j.at < MAX_AGE && Number.isInteger(j.failed) && Number.isInteger(j.total)) {
        real = [null, String(j.failed), String(j.total)];
        console.log('· clicks.js — מהריצה שלפני ' + Math.round((Date.now() - j.at) / 1000) + ' שניות, לא הורץ שוב');
      }
    } catch (e) { /* אין סיכום — מריצים */ }
    if (!real) {
      let out = '';
      try {
        out = execFileSync(process.execPath, [path.join(__dirname, 'clicks.js')],
                           { encoding: 'utf8', cwd: ROOT });
      } catch (e) { out = (e.stdout || '') + (e.stderr || '') }
      real = out.match(/(\d+)\s*מתוך\s*(\d+)\s*לא מקריאות/);
    }
    if (!real) { stale++; console.log('✗ clicks.js לא החזיר מספר שאפשר להשוות') }
    else if (real[1] !== m[1] || real[2] !== m[2]) {
      stale++;
      console.log(`✗ marketing/facts.md מצטט ${m[1]} מתוך ${m[2]} ל-clicks.js, והפקודה מחזירה ${real[1]} מתוך ${real[2]}`);
      console.log('    טענה שנשענת על מדידה מתיישנת לשני הכיוונים — גם איסור יכול להתיישן');
    }
  }
}
console.log(`${stale ? '✗' : '✓'} המספרים שמצוטטים מפקודה תואמים למה שהפקודה מחזירה היום`);

process.exit(bad || stale ? 1 : 0);
