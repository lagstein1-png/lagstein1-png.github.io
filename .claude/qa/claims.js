/* =====================================================================
   claims.js — חמש הטענות שאסור לנו, ומה שמבדיל ביניהן

     node .claude/qa/claims.js

   **מאיפה הרשימה.** הבעלים מסר אותה 15.9.2026, והיא ישבה עד אז
   ב-`marketing/campaign.md` — קובץ בן 52KB, שלא נקרא לפני כל
   טקסט. עכשיו היא ב-`marketing/facts.md`, ובדיקה אוכפת אותה.

   **והחלוקה לשתי משפחות היא כל העניין כאן.**

   שתיים מהחמש הן **מדידה**: ״כל לחיצה מוקראת״ ו״עובד אופליין״.
   הן נכונות או שגויות לפי מה שהפקודה מחזירה היום, והן **מתיישנות
   לשני הכיוונים**. נמדד בסשן הזה: הטענה הראשונה נאסרה בנימוק
   ״`clicks.js` מדווח 5 מתוך 12״, ובינתיים `O-55` נסגר ואותה
   פקודה מדווחת **0 מתוך 12 שאינן מקריאות** — כלומר האיסור עצמו
   התיישן, והטקסט השיווקי המשיך לצטט מספר מת. לכן הבדיקה כאן
   **מריצה את הפקודה** ואינה סומכת על המספר שכתוב.

   שלוש מהחמש הן **היעדר ראיה**: ״תואם קוראי מסך״, ״עומד ב-WCAG
   2.2 AA״, ו״מתאים לדיסלקציה״ כהתאמה מקצועית. הן אינן יכולות
   להפוך נכונות משינוי בקוד — רק מהרצת NVDA מקצה לקצה, מביקורת
   חיצונית, או מאיש מקצוע. **לכן הן נאסרות בגרפ, לתמיד.**

   **מה שמותר ואינו נתפס כאן:** לתאר מה הכלי עושה. ״כל שאלה
   מוקראת״, ״אפשר להגדיל טקסט ולהחליף גופן״, ״נבנה בשביל מי
   שקשה לו לקרוא״ — כולם תיאור ולא הצהרה, וכולם עוברים.
   ===================================================================== */
const fs = require('fs'), path = require('path');
const { execFileSync } = require('child_process');
const ROOT = path.resolve(__dirname, '..', '..');

let bad = 0;
const fail = m => { bad++; console.log('✗ ' + m) };

/* ---------------------------------------------------------------
   אילו קבצים נסרקים.

   **מה שאינו נסרק, ולמה.** `FINDINGS.md` ו-`CHANGELOG.md` הם
   יומנים: הם מתעדים מה נאמר ומתי, ואיסור עליהם היה מוחק
   היסטוריה. `ACCESSIBILITY.md` הוא מפרט פנימי שמפנה לסעיפי
   WCAG כמקור, ולא מצהיר עמידה. והרשימה עצמה ב-`facts.md`
   מצטטת את הטענות כדי לאסור אותן.
   --------------------------------------------------------------- */
const SKIP = /^(FINDINGS|CHANGELOG|ACCESSIBILITY|BRANDING|JOSH|FACE|PIPELINE|NAMING|STATUS|GUIDE|ARCHITECTURE|ARTHUR|CLAUDE|README)\.md$/;
const files = [];
(function walk(dir, depth) {
  if (depth > 2) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (/^(\.git|node_modules|\.claude)$/.test(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { walk(p, depth + 1); continue }
    if (!/\.(md|html)$/.test(e.name)) continue;
    if (depth === 0 && SKIP.test(e.name)) continue;
    files.push(p);
  }
})(ROOT, 0);

/* ---------------------------------------------------------------
   מתי שורה **מצטטת** טענה ומתי היא **טוענת** אותה.

   **הסימן המדויק הוא מירכאות עבריות ״…״.** זו הקונבנציה של
   המאגר הזה לציטוט, והיא חדה יותר מרשימת מילות מפתח: הרשימה
   הראשונה שכתבתי כאן פספסה שתי שורות ב-`facts.md` שמצטטות את
   הטענה בשורה אחת ומנמקות בשורה הבאה — כלומר **הבדיקה האשימה
   את האיסור עצמו**.

   שתי דרכים, ושתיהן נדרשות: הטקסט שנתפס יושב בתוך ״…״, או
   שהשורה נושאת מילת איסור מפורשת. */
const QUOTING = /אסור|לא נכון|אין ביקורת|לא נמדד|אל תכתבו|נאסר|אין תעודה|מותר במקומה|במקומה:/;
function quoted(line, m) {
  if (QUOTING.test(line)) return true;
  /* האם ההתאמה נמצאת בתוך זוג מירכאות עבריות באותה שורה */
  const i = line.indexOf(m);
  if (i < 0) return false;
  const before = line.slice(0, i), after = line.slice(i);
  return /\u05F4/.test(before) && /\u05F4/.test(after);
}

/* ---------------------------------------------------------------
   שלוש הטענות שהן היעדר ראיה. כל אחת: מה נאסר, ומה מותר במקומה.
   --------------------------------------------------------------- */
const FORBIDDEN = [
  { id: 'קוראי מסך',
    re: /(תואם|תומך ב|נתמך ב|מותאם ל)\s*קורא[יא]?\s*מסך|screen[- ]reader\s*(compatible|ready|tested)|נגיש לעיוורים/,
    why: 'אף אחד לא הריץ NVDA או VoiceOver מקצה לקצה',
    ok: 'אפשר לתאר את ה-ARIA ואת ניווט המקלדת, ולומר מה נבדק' },

  { id: 'WCAG',
    re: /(עומד|עומדת|תואם|תואמת|עמידה|בהתאם)\s*(ב-?|ל-?)?\s*WCAG|WCAG[^.\n]{0,24}(compliant|conformant|certified)/i,
    why: 'יש בדיקות פנימיות בלבד — אין תעודה ואין גורם חיצוני',
    ok: 'אפשר להפנות לסעיף WCAG כמקור, ולומר מה נמדד פנימית' },

  { id: 'דיסלקציה כהתאמה',
    re: /(מתאים|מותאם|מיועד|מאושר|נבדק)\s*(ל|עבור)\s*(דיסלקצ|ADHD|לקויות למידה)|מותאם ללקויות למידה/,
    why: 'זו הצהרה מקצועית, ואין מאחוריה איש מקצוע',
    ok: 'אפשר לתאר מה הכלי עושה, ולתת לקורא להחליט' },

  { id: 'אופליין מוחלט',
    re: /(לגמרי|לחלוטין|הכול|הכל|תמיד)\s*(עובד\s*)?אופליין|עובד\s*(לגמרי|לחלוטין)\s*(בלי|ללא)\s*(אינטרנט|רשת)|fully\s+offline/,
    why: 'שני חריגים: הניקוד ב-reader והקול המשודרג',
    ok: '״עובד אופליין; הניקוד האוטומטי והקול המשודרג דורשים רשת״' }
];

for (const f of files) {
  const rel = path.relative(ROOT, f).replace(/\\/g, '/');
  const lines = fs.readFileSync(f, 'utf8').split('\n');
  lines.forEach((l, i) => {
    for (const c of FORBIDDEN) {
      const m = l.match(c.re);
      if (!m) continue;
      if (quoted(l, m[0])) continue;
      fail(`${rel}:${i + 1} — טענת ״${c.id}״: ${c.why}`);
      console.log(`    ${l.trim().slice(0, 92)}`);
      console.log(`    מותר במקומה: ${c.ok}`);
    }
  });
}
console.log(`${bad ? '✗' : '✓'} ${files.length} קבצים נסרקו, ${bad} טענות אסורות`);

/* ---------------------------------------------------------------
   והשתיים שהן מדידה: הפקודה רצה, והמספר שבטקסט מושווה אליה.

   זה מה שמונע מהרשימה עצמה להתיישן — בדיוק מה שקרה כאן.
   --------------------------------------------------------------- */
let stale = 0;
const facts = path.join(ROOT, 'marketing', 'facts.md');
if (fs.existsSync(facts)) {
  const txt = fs.readFileSync(facts, 'utf8');
  /* **רק השורה שטוענת, לא זו שמצטטת.** הסעיף ב-`facts.md` מסביר
     שהאיסור הישן התיישן, ולשם כך הוא מצטט את המספר המת — ובלי
     הסינון הזה הבדיקה הייתה נופלת על ההסבר עצמו. */
  const m = txt.split('\n')
    .filter(l => /clicks\.js/.test(l) && /\d+\s*מתוך\s*\d+/.test(l))
    .map(l => ({ l: l, hit: l.match(/(\d+)\s*מתוך\s*(\d+)/) }))
    .filter(x => x.hit && !quoted(x.l, x.hit[0]))
    .map(x => x.hit)[0];
  if (m) {
    let out = '';
    try {
      out = execFileSync(process.execPath, [path.join(__dirname, 'clicks.js')],
                         { encoding: 'utf8', cwd: ROOT });
    } catch (e) { out = (e.stdout || '') + (e.stderr || '') }
    const real = out.match(/(\d+)\s*מתוך\s*(\d+)\s*לא מקריאות/);
    if (!real) { stale++; console.log('✗ clicks.js לא החזיר מספר שאפשר להשוות') }
    else if (real[1] !== m[1] || real[2] !== m[2]) {
      stale++;
      console.log(`✗ marketing/facts.md מצטט ${m[1]} מתוך ${m[2]} ל-clicks.js, והפקודה מחזירה ${real[1]} מתוך ${real[2]}`);
      console.log('    טענה שנשענת על מדידה מתיישנת לשני הכיוונים — גם איסור יכול להתיישן');
    }
  }
}
console.log(`${stale ? '✗' : '✓'} המספרים שמצוטטים מפקודה תואמים למה שהפקודה מחזירה היום`);

process.exit(bad || stale ? 1 : 0);
