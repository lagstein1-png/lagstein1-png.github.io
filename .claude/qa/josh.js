'use strict';
const fs = require('fs'), path = require('path');
const { execFileSync } = require('child_process');
const ROOT = process.argv[2] ? path.resolve(process.argv[2]) : path.resolve(__dirname, '..', '..');
const TEXT = /\.(html|js|json|md|css|svg|txt|webmanifest|yml|yaml|sh|toml|patch)$/i;

/* כל גרש שאינו U+05F3 בין ה-ג ל-וש */
const WRONG = /ג['‘’`]וש/;

/* קובץ באמצע מיזוג מופיע ב-ls-files שלוש פעמים — נספר פעם אחת */
const files = [...new Set(execFileSync('git', ['ls-files', '-z'], { cwd: ROOT }).toString().split('\0'))]
  .filter(f => f && TEXT.test(f) && f !== '.claude/qa/josh.js');

let bad = 0, hits = 0;
for (const f of files) {
  const full = path.join(ROOT, f);
  if (!fs.existsSync(full)) continue;
  const lines = fs.readFileSync(full, 'utf8').split('\n');
  let n = 0;
  lines.forEach((ln, i) => {
    if (WRONG.test(ln)) { n++; hits++; console.log(`✗ ${f}:${i + 1}: ${ln.trim().slice(0, 60)}`); }
  });
  if (n) bad++;
}

console.log(`${bad ? '✗' : '✓'} ${files.length} קבצי טקסט נסרקו, ${bad} עם כתיב שאינו הגרש העברי (${hits} שורות)`);
if (bad) console.log('  הכתיב הוא ג׳וש בגרש עברי U+05F3 — ראו JOSH.md, סעיף ״הכתיב״');
process.exit(bad ? 1 : 0);
