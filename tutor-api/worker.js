function revealsAnswer(text, ans) {
  if (ans === null || ans === undefined || ans === "") return false;
  const s = String(ans).trim();
  if (!s) return false;
  if (/^-?\d+(\.\d+)?$/.test(s))
    /* **הנקודה שמסיימת משפט אינה נקודה עשרונית.** הביטוי הקודם
       הוציא `.` משני הצדדים — `(^|[^\d.])15([^\d.]|$)` — כדי
       ש-״15״ לא ייתפס בתוך ״0.15״ או ״15.7״. המחיר היה ש-״התשובה
       היא 15.״ חמק, וזו הדרך הטבעית ביותר שמודל מוסר תשובה.
       נמדד 10.9.2026: שש מתוך אחת עשרה צורות מסירה חמקו.
       היום ההוצאה ממוקדת — ספרה אחרי הנקודה, ולא כל נקודה. */
    return new RegExp("(?<![\\d.])" + s.replace(".", "\\.") +
                      "(?!\\d)(?!\\.\\d)").test(text);
  /* תשובה מילולית: נחשבת חשופה רק אם היא מופיעה במלואה, ורק אם
     היא ארוכה מספיק כדי שלא תהיה מילת קישור מקרית.

     ההשוואה מתעלמת מאותיות השימוש — ״המהפכה״ מול ״למהפכה״ הוא
     אותו דבר לענייננו, ובלי זה כל תשובה בעברית הייתה חומקת מהשומר
     בגלל ו׳ אחת בהתחלה. אות שימוש מוסרת רק אם נשארת מילה של שלוש
     אותיות לפחות, כדי לא לרסק מילים קצרות. */
  return s.length >= 3 && strip(text).indexOf(strip(s)) >= 0;
}

function strip(txt) {
  return String(txt).replace(/[\u0591-\u05C7]/g, "")          /* ניקוד וטעמים */
    .split(/\s+/)
    .map(w => /^[\u05D5\u05D4\u05D1\u05DC\u05DB\u05DE\u05E9]/.test(w) && w.length >= 4
              ? w.slice(1) : w)
    .join(" ").trim();
}

/* המספרים כאן עשרוניים ולא שלמים, ולכן `\d+(\.\d+)?` ולא `\d+`.
   עם `\d+` בלבד, ״1/2 = 0.5״ נקרא כ-״1/2 = 0״ ונפסל — כלומר
   המורה אמר דבר נכון והשומר זרק אותו. נמדד: גם ״10 : 4 = 2.5״.
   וההשוואה בסבילות, כי 0.1+0.2 אינו 0.3 בנקודה צפה. */
const NUM = "(\\d+(?:\\.\\d+)?)";
function badEquation(text) {
  const re = new RegExp(NUM + "\\s*([+\\-−×xX*÷:/])\\s*" + NUM + "\\s*=\\s*" + NUM, "g");
  let m;
  while ((m = re.exec(text))) {
    const a = +m[1], b = +m[3], said = +m[4];
    let real;
    if (m[2] === "+") real = a + b;
    else if (m[2] === "-" || m[2] === "−") real = a - b;
    else if (m[2] === "÷" || m[2] === ":" || m[2] === "/") { if (!b) return true; real = a / b; }
    else real = a * b;
    /* שלושה שלמים — השוואה מדויקת. סבילות יחסית הייתה מפספסת
       ״100 + 200 = 301״, טעות של אחד שהיא 0.33% בלבד.
       יש עשרוני — סבילות של 0.011, שזה בדיוק עיגול לשתי ספרות:
       ״1 : 3 = 0.33״ עובר, ״2.5 + 2.5 = 6״ נפסל. */
    const whole = m[1].indexOf(".") < 0 && m[3].indexOf(".") < 0 && m[4].indexOf(".") < 0;
    if (whole ? real !== said : Math.abs(real - said) > 0.011) return true;
  }
  return false;
}

