const FLUSH_MS = 10 * 60 * 1000;
const FLUSH_EVERY = 25;
const IP_MAP_MAX = 5000;
function dayKey() { return new Date().toISOString().slice(0, 10) }
const RATE_MEM = { day: "", ip: new Map(), g: { base: 0, pending: 0, readAt: 0, flushAt: 0 }, writes: 0 };
function rollDay() {
  const d = dayKey();
  if (RATE_MEM.day !== d) {
    RATE_MEM.day = d; RATE_MEM.ip.clear();
    RATE_MEM.g = { base: 0, pending: 0, readAt: 0, flushAt: 0 };
  }
}
function capOfEnv(env, name, dflt) {
  const v = env && env[name] != null ? parseInt(env[name], 10) : NaN;
  return v > 0 ? v : dflt;
}
function flushGlobal(env, ctx, force) {
  if (!env.RATE) return null;
  const now = Date.now();
  if (!force && RATE_MEM.g.pending < FLUSH_EVERY && now - RATE_MEM.g.flushAt < FLUSH_MS) return null;
  const add = RATE_MEM.g.pending, key = "g:" + RATE_MEM.day;
  RATE_MEM.g.pending = 0; RATE_MEM.g.flushAt = now;
  const p = (async () => {
    const cur = +(await env.RATE.get(key) || 0);
    const val = cur + add;
    RATE_MEM.writes++;
    await env.RATE.put(key, String(val), { expirationTtl: 172800 });
    RATE_MEM.g.base = val; RATE_MEM.g.readAt = Date.now();
  })().catch(() => { RATE_MEM.g.pending += add });
  if (ctx && typeof ctx.waitUntil === "function") ctx.waitUntil(p);
  return p;
}
/* קריאה בלבד, בלי לכתוב ובלי לצרוך מהתקרה — הבעלים שאל "מה יש
   ב-KV עכשיו", ולנקודת הקצה שהייתה כאן (`/health`) לא היה מה
   לענות: היא ידעה רק אם RATE מחובר, לא כמה נוצל. קריאת KV אחת,
   טרייה בכל פעם — לא נשענת על RATE_MEM, כי isolate טרי (זה
   שמקבל את בקשת /health עצמה) לא בהכרח ראה עדיין אף /ask וה-
   base שלו נשאר 0 גם כשה-KV האמיתי כבר גבוה יותר. */
async function currentUsage(env) {
  if (!env.RATE) return null;
  const day = dayKey();
  const cap = capOfEnv(env, "GLOBAL_PER_DAY", LIM.globalPerDay);
  try {
    const used = +(await env.RATE.get("g:" + day) || 0);
    return { day, used, cap, remaining: Math.max(0, cap - used) };
  } catch (e) {
    return { day, used: null, cap, error: "kv-read-failed" };
  }
}
async function overLimit(env, ip, ctx) {
  if (!env.RATE) return null;                     /* הוצהר במפורש — ראו noCounter */
  rollDay();
  const perDay = capOfEnv(env, "PER_DAY", LIM.perDay);
  const globalPerDay = capOfEnv(env, "GLOBAL_PER_DAY", LIM.globalPerDay);
  const ipKey = "ip:" + RATE_MEM.day + ":" + ip;

  /* קיצור דרך זול: אם הזיכרון המקומי כבר יודע שנגמר — אין טעם
     לקרוא ל-KV. אחרת ה-KV הוא הבודק, כי isolate אחר יכול לדעת
     יותר ממה שיש כאן בזיכרון. */
  let n = RATE_MEM.ip.get(ip) || 0;
  if (n < perDay) {
    try {
      const kvN = +(await env.RATE.get(ipKey) || 0);
      if (kvN > n) n = kvN;
    } catch (e) { return "all" }              /* KV תקול — נכשל-סגור */
  }
  if (n >= perDay) { RATE_MEM.ip.set(ip, n); return "you" }

  const now = Date.now();
  if (!RATE_MEM.g.readAt || now - RATE_MEM.g.readAt > FLUSH_MS) {
    try {
      const base = +(await env.RATE.get("g:" + RATE_MEM.day) || 0);
      if (base > RATE_MEM.g.base) RATE_MEM.g.base = base;
    } catch (e) { return "all" }              /* KV תקול — נכשל-סגור */
    RATE_MEM.g.readAt = now;
  }
  if (RATE_MEM.g.base + RATE_MEM.g.pending >= globalPerDay) return "all";

  if (RATE_MEM.ip.size >= IP_MAP_MAX) RATE_MEM.ip.clear();
  RATE_MEM.ip.set(ip, n + 1);
  RATE_MEM.g.pending++;
  flushGlobal(env, ctx, false);
  /* כתיבת ה-IP ל-KV: best-effort ולא חוסמת את התשובה ללומד.
     כשלון כתיבה משאיר את הספירה נשענת על הזיכרון המקומי בלבד
     עד ה-isolate הבא — נסיגה להתנהגות הישנה, לא כשל חדש. */
  const w = env.RATE.put(ipKey, String(n + 1), { expirationTtl: 172800 }).catch(() => {});
  if (ctx && typeof ctx.waitUntil === "function") ctx.waitUntil(w); else await w;
  return null;
}
