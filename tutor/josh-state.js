/* =====================================================================
   josh-state.js — מצב הלומד. גלאי, ולא מוח.

   **מה הקובץ הזה עושה.** הוא מקבל תוצאות של שאלות — נכון/לא־נכון,
   כמה זמן לקח, והאם נפתח רמז — ומחזיר מילה אחת מתוך ארבע:

       ok · slow · stuck · frustrated

   זה הכול. הוא אינו יודע מה נלמד, אינו יודע מה השאלה הבאה, אינו
   בוחר רמה ואינו כותב טקסט. המוח היחיד הוא `tutor-api/worker.js`,
   והממשק אליו הוא `tutor/tutor.js`. הקובץ הזה הוא הצד השלישי של
   אותה הפרדה: `josh-face.js` מצייר, `josh-state.js` מודד,
   ו-`worker.js` בשרת הוא היחיד שמחליט.

   `node .claude/qa/joshstate.js` אוכף את זה בקוד ולא בהבטחה — הוא
   גם קורא את הקובץ וגם **מריץ** אותו מול תרחישים, מפני שגלאי
   שנכתב נכון ומתנהג לא נכון הוא עדיין תקלה.

   ── שלוש החלטות שצריך להכיר לפני שנוגעים ──

   **1. ״איטי״ נמדד מול הלומד עצמו, ולא מול שעון.**
   זו ההחלטה החשובה כאן, והיא נובעת מקהל היעד: דיסלקציה, ADHD,
   ועולים חדשים שקוראים שאלה בשפה שנייה. סף מוחלט — ״יותר מ-20
   שניות זה איטי״ — היה מתייג את כולם כאיטיים לתמיד, בכל שאלה,
   מהרגע הראשון. זה אינו סימן למידה אלא תווית.

   לכן הבסיס הוא **החציון של אותו לומד באותו מפגש**, ו-`slow`
   נדלק רק כשהשאלה האחרונה ארוכה משמעותית מהקצב שלו עצמו. לומד
   שקורא לאט יישאר `ok` כל עוד הוא עקבי; מה שמדובר עליו הוא
   **שינוי**, ושינוי הוא סימן למידה.

   וחציון ולא ממוצע: שאלה אחת שבה מישהו קם להביא כוס מים מזיזה
   ממוצע ולא מזיזה חציון.

   **2. בלי בסיס אין ״איטי״.** מתחת ל-`SLOW_MIN` שאלות אין חציון
   שאפשר להישען עליו, והמצב הוא `ok`. גלאי שמכריז על הלומד בשאלה
   הראשונה מכריז על הרעש.

   **3. אין `localStorage`, ואין שום אחסון.** ״מקומי למפגש״ —
   לשונו של הבעלים. המצב חי בזיכרון, סגירת הלשונית שוכחת אותו,
   וזו אינה מגבלה אלא הגדרה: תסכול של אתמול אינו נתון על הלומד.
   ובדרך זה גם מוציא אותנו מ״מלכודת ה-localStorage״ שכבר תפסה
   כאן ארבע אפליקציות — אין מפתח, אין מגירה משותפת.

   ── והאיסור המפורש: מבחן כיתתי ──

   הבעלים אסר את זה בשלב 3 במפורש, והסיבה מבנית. בונה המבחן אורז
   **זרע** לתוך הקישור, והתלמיד בונה מהזרע את אותן שאלות אצלו —
   ולכן כל דבר שנכנס לבחירת השאלה חייב להיות זהה בשני הצדדים.
   מצב הלומד שונה אצל כל אחד בהגדרה, ולכן שאלה שתלויה בו היא
   שאלה שהמורה אישר ואינה זו שהכיתה נבחנת בה. זה כבר קרה כאן
   פעם אחת דרך `chooseIndex` — 39 שאלות מתוך 200 יצאו שונות,
   ואיש לא ראה, מפני ששני המסכים היו תקינים.

   לכן `off()` אינו הצעה. בזמן מבחן: `JOSHSTATE.off()` בכניסה,
   `JOSHSTATE.on()` ביציאה. **וכשהוא כבוי `answer()` אינו רושם
   דבר** — לא ״רושם ולא מדווח״, אלא לא רושם. כך מבחן אינו משאיר
   שובל שישנה את הדיווח אחריו.

   שימוש:

     <script src="/tutor/josh-state.js"></script>

     JOSHSTATE.reset();                        // מפגש חדש
     JOSHSTATE.answer({ ok:true, ms:4200 });   // שאלה נענתה
     JOSHSTATE.hint();                         // הלומד פתח רמז
     JOSHSTATE.state();                        // "ok" | "slow" | "stuck" | "frustrated"
     JOSHSTATE.off();                          // מבחן כיתתי — ראו למעלה
   ===================================================================== */
(function (g) {
"use strict";

/* ארבעה, ואין חמישי. הסדר הוא סדר החומרה, והוא גם סדר ההכרעה
   ב-`state()` למטה: הראשון שמתקיים הוא התשובה. */
var STATES = ["frustrated", "stuck", "slow", "ok"];

/* ---------------------------------------------------------------
   הספים. כל אחד מהם מספר, ולכן כל אחד מהם צריך נימוק — אחרת
   מישהו ישנה אותו בעוד חודש ולא יֵדע מה הוא שובר.
   --------------------------------------------------------------- */

/* שתי שאלות רצופות שגויות הן ״נתקע״, שלוש הן ״מתוסכל״. למה רצופות
   ולא אחוז: אחוז מתאר את המפגש כולו, ומי שיושב מול המסך נמצא
   ברגע. לומד שענה עשר נכון וחמש לא — אינו תקוע אם החמש היו
   בהתחלה. */
var WRONG_STUCK      = 2;
var WRONG_FRUST      = 3;

/* רמז אינו כישלון, וזה לא סגנון: פתיחת רמז היא בדיוק ההתנהגות
   שהאפליקציות האלה מבקשות. לכן רמז לבדו אינו מדליק כלום, ורק
   **רמז יחד עם טעות** על אותה שאלה נחשב סימן. */
var HINT_WITH_WRONG  = 2;
/* ועל ארבע השאלות האחרונות בלבד, ולא על החלון כולו. נמדד בדפדפן
   13.9.2026: במצב רגוע כל טעות ראשונה פותחת רמז מעצמה, ולכן שלוש
   שאלות שגויות הותירו שלושה סימני רמז־עם־טעות — ואלה נשארו בחלון
   שמונה שאלות שלמות. לומד שענה אחריהן ארבע נכון ברצף עדיין דווח
   `stuck`, כלומר לא הייתה לו דרך לצאת מזה בתוך החלון. מצב הלומד
   אמור לתאר את הרגע, והרגע חייב להיות ניתן לשינוי. */
var HINT_RECENT      = 4;

/* פי כמה מהחציון של הלומד עצמו. 2.2 ולא 1.5: תנודה טבעית בין
   שאלה לשאלה גדולה, ו-1.5 היה מדליק `slow` על כל שאלה ארוכה
   קצת. */
var SLOW_FACTOR      = 2.2;
/* מתחת לזה אין חציון, ואין ״איטי״. */
var SLOW_MIN         = 4;
/* קצר מזה אינו מדידת קצב אלא לחיצה — לומד שמדלג. לא נכנס לחציון. */
var MS_FLOOR         = 400;

/* החלון: כמה שאלות אחרונות נשקלות. מפגש שלם היה גורר לתוך הרגע
   הזה טעויות משאלה ראשונה, וזה בדיוק מה שמורה אנושי אינו עושה. */
var WINDOW           = 8;

/* ---------------------------------------------------------------
   המצב. בזיכרון, ואין אחסון — ראו החלטה 3 למעלה.
   --------------------------------------------------------------- */
var live = true;          /* `off()` בזמן מבחן כיתתי */
var log  = [];            /* { ok:bool, ms:number|null, hint:bool } */
/* `hint()` מגיע **לפני** ה-`answer()` של אותה שאלה — הלומד פותח רמז
   ואחר כך עונה — ולכן הוא ממתין כאן עד שהשאלה נסגרת. */
var pendingHint = false;

function trim() { if (log.length > WINDOW) log = log.slice(-WINDOW) }

function median(a) {
  if (!a.length) return 0;
  var s = a.slice().sort(function (x, y) { return x - y });
  var m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

/* כמה שאלות שגויות ברצף, מהסוף אחורה. */
function wrongRun() {
  var n = 0;
  for (var i = log.length - 1; i >= 0 && !log[i].ok; i--) n++;
  return n;
}

/* הזמנים שראויים להיכנס לחציון: מספר אמיתי, ומעל רצפת הלחיצה. */
function times() {
  var out = [], i;
  for (i = 0; i < log.length; i++)
    if (typeof log[i].ms === "number" && log[i].ms >= MS_FLOOR) out.push(log[i].ms);
  return out;
}

g.JOSHSTATE = {

  /* מפגש חדש, נושא חדש, רמה חדשה — מה שהאפליקציה מחשיבה כהתחלה.
     מוחק את החלון ואינו נוגע ב-`live`: מבחן שכבוי נשאר כבוי. */
  reset: function () { log = []; pendingHint = false; return true },

  /* שאלה נענתה. `ok` חובה, `ms` רשות (בלי שעון אין `slow`, וזה
     תקין — שלושת האחרים עדיין עובדים).

     **נקרא פעם אחת לכל שאלה, לא לכל לחיצה.** שאלה שנענתה לא־נכון
     פעמיים היא שאלה אחת שגויה, לא שתיים; אחרת `wrongRun` מגיע
     ל-3 מתוך שאלה אחת ו-`frustrated` נדלק על מי שרק טעה פעם. */
  answer: function (o) {
    if (!live) return false;
    if (!o || typeof o.ok !== "boolean") return false;
    var ms = (typeof o.ms === "number" && isFinite(o.ms) && o.ms >= 0) ? o.ms : null;
    log.push({ ok: o.ok, ms: ms, hint: !!o.hint || pendingHint });
    pendingHint = false;
    trim();
    return true;
  },

  /* הלומד פתח רמז בשאלה הנוכחית. נרשם על השאלה האחרונה אם היא
     עדיין פתוחה — כלומר אם `hint()` הגיע לפני ה-`answer()` שלה,
     נשמר וייכנס אליה. */
  hint: function () {
    if (!live) return false;
    pendingHint = true;
    return true;
  },

  /* המילה. אחת מארבע, לעולם לא `null` ולעולם לא `undefined`:
     גלאי כבוי אומר ״אין לי מה לדווח״, ולא ״לא יודע״ — אחרת כל
     קורא היה צריך ענף משלו, וענף כזה נשכח. */
  state: function () {
    if (!live || !log.length) return "ok";

    var run = wrongRun();
    if (run >= WRONG_FRUST) return "frustrated";

    /* רמז **יחד עם** טעות, על אותה שאלה, בארבע האחרונות. */
    var recent = log.slice(-HINT_RECENT), hw = 0, i;
    for (i = 0; i < recent.length; i++) if (recent[i].hint && !recent[i].ok) hw++;
    if (run >= WRONG_STUCK || hw >= HINT_WITH_WRONG) return "stuck";

    var t = times();
    if (t.length >= SLOW_MIN) {
      var last = log[log.length - 1].ms;
      if (typeof last === "number" && last >= MS_FLOOR) {
        /* החציון **בלי** השאלה האחרונה: אחרת היא מושכת את הבסיס
           שאליו היא מושווית, וככל שהיא חריגה יותר כך היא מסתירה
           את עצמה טוב יותר. */
        var base = median(t.slice(0, -1));
        if (base > 0 && last > base * SLOW_FACTOR) return "slow";
      }
    }
    return "ok";
  },

  /* המספרים הגולמיים. נועד לשלב 4 — מה שנשלח ל-`CORE` שבשרת —
     ולאבחון. **אינו** כולל את תוכן השאלות: הגלאי אינו רואה אותן
     ואין לו מה למסור עליהן. */
  snapshot: function () {
    var t = times();
    return {
      live: live,
      n: log.length,
      wrongRun: wrongRun(),
      medianMs: t.length ? median(t) : null,
      state: this.state()
    };
  },

  /* מבחן כיתתי. `off()` מפסיק לרשום — ראו ״האיסור המפורש״ למעלה. */
  off: function () { live = false; return true },
  on:  function () { live = true;  return true },
  live: function () { return live },

  /* לבדיקות, ולתיעוד: ארבע ואין חמישית. */
  states: function () { return STATES.slice() }
};

})(typeof globalThis !== "undefined" ? globalThis : this);
