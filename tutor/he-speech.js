(function (g) {
  "use strict";

  /* כתיב חסר → כתיב מלא, ומילים שהגיעו מנוקדות מהמקור.
     39 כניסות, מיוצאות מ-data/speech-rules.json של הריפו הנפרד. */
  var KTIV = {"לעצר": "לעצור", "בעצר": "בעצור", "מתמן": "מתומן", "משלש": "משולש", "המשלש": "המשולש", "מצין": "מצוין", "מאד": "מאוד", "מלה": "מילה", "המלה": "המילה", "חצייה": "חֲצִיָּיה", "החצייה": "הַחֲצִיָּיה", "בחצייה": "בַּחֲצִיָּיה", "לחצייה": "לַחֲצִיָּיה", "נסע": "נָסַע", "לנסוע": "לִנְסוֹעַ", "לעבור": "לַעֲבוֹר", "ירד": "יָרַד", "לרדת": "לָרֶדֶת", "עלה": "עָלָה", "לעלות": "לַעֲלוֹת", "מהר": "מַהֵר", "חצי": "חֲצִי", "דרך": "דֶּרֶךְ", "מהירות": "מְהִירוּת", "עצירה": "עֲצִירָה", "לעצור": "לַעֲצוֹר", "בעצירה": "בַּעֲצִירָה", "אסור": "אָסוּר", "מותר": "מוּתָּר", "חובה": "חוֹבָה", "במשלש": "במשולש", "למשלש": "למשולש", "ומשלש": "ומשולש", "שמשלש": "שמשולש", "משלשים": "משולשים", "המשלשים": "המשולשים", "משלשי": "משולשי", "המתמן": "המתומן", "במתמן": "במתומן", "מתמנים": "מתומנים", "ומאד": "ומאוד", "מלים": "מילים", "המלים": "המילים", "במלה": "במילה", "למלה": "למילה"};

  /* ספרות שבתוך מזהה נקראות ספרה-ספרה. מספר בתוך משפט הוא כמות
     ונשאר כפי שהוא — ״8 + 7״ אינו ״שמונה ועוד שבע״ כאן, זה תפקידו
     של speakMath שבאפליקציה. */
  var DIGITS = ["אפס", "אחת", "שתיים", "שלוש", "ארבע", "חמש", "שש", "שבע", "שמונה", "תשע"];
  var UNITS  = ["קמ\"ש", "קמ״ש", "קמש", "ק\"מ", "ק״מ", "מטרים", "מטר", "מ'", "מ׳", "ס\"מ", "ס״מ", "סנטימטרים", "טון", "ק\"ג", "ק״ג", "קילוגרם", "שניות", "שנייה", "דקות", "דקה", "שעות", "שעה", "שנים", "שנה", "חודשים", "חודש", "אחוז", "אחוזים", "%"];
  var CODES  = ["[0-9]{3,}", "[0-9]{3,}(?:, *[0-9]{3,})+", "[א-ת]-?[0-9]+", "[0-9]+[א-ת]"];
  var LETTER = /[א-ת]/;

  var HEB = /[\u05D0-\u05EA]/;
  var NIQQUD = /[\u0591-\u05C7]/g;
  var SPLIT = /(\s+)/;

  function spellDigits(s) {
    return s.replace(/[0-9]+/g, function (dgt, i, str) {
      var before = i > 0 ? str[i - 1] : "";
      var after  = str[i + dgt.length] || "";
      return (LETTER.test(before) ? " " : "") +
             dgt.split("").map(function (c) { return DIGITS[+c] || c }).join(" ") +
             (LETTER.test(after) ? " " : "");
    });
  }

  function wholeIsCode(text) {
    var t = String(text).trim();
    for (var i = 0; i < UNITS.length; i++) if (t.indexOf(UNITS[i]) >= 0) return false;
    return new RegExp("^(?:" + CODES.join("|") + ")$").test(t);
  }

  /* אסימון אחד. הראשון שמכריע מנצח — בדיוק סדר השכבות שבמקור. */
  function token(tk, code) {
    var bare = tk.replace(NIQQUD, "");
    if (code && /[0-9]/.test(bare)) return spellDigits(bare);
    if (KTIV[bare]) return KTIV[bare];
    /* סימני פיסוק דבוקים: ״משולש,״ — מטפלים בגזע ומחזירים את הזנב */
    var m = /^([\u05D0-\u05EA]+)([^\u05D0-\u05EA]*)$/.exec(bare);
    if (m && KTIV[m[1]]) return KTIV[m[1]] + m[2];
    return tk;
  }

  /* המחרוזת הנאמרת. מספר האסימונים זהה לקלט — ראו הערת הראש. */
  function spoken(text) {
    var src = String(text == null ? "" : text);
    if (!HEB.test(src)) return src;
    var code = wholeIsCode(src);
    var parts = src.split(SPLIT), out = "", i;
    for (i = 0; i < parts.length; i++) {
      out += /^\s*$/.test(parts[i]) ? parts[i] : token(parts[i], code);
    }
    return out;
  }

  /* זוגות מוצג/נאמר, לפי אסימון — מה ש-hlPrep צריך כדי למפות
     הדגשה כשהאורכים נבדלים. */
  function pairs(text) {
    var src = String(text == null ? "" : text);
    var code = HEB.test(src) && wholeIsCode(src);
    var parts = src.split(SPLIT), out = [], i;
    for (i = 0; i < parts.length; i++) {
      if (/^\s*$/.test(parts[i])) continue;
      out.push({ d: parts[i], s: HEB.test(src) ? token(parts[i], code) : parts[i] });
    }
    return out;
  }

  g.HESPEECH = { spoken: spoken, pairs: pairs, _ktiv: KTIV };
})(typeof window !== "undefined" ? window : globalThis);
