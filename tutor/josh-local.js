/* מונה מחזורי לכל כוונה, כדי שהנוסח השני יהיה שונה מהראשון. */
var turn = {};
function pick(list, id) {
  if (!list || !list.length) return "";
  if (list.length === 1) return list[0];
  /* **הראשון הוא הראשון.** הניסוח הקודם קידם את המונה לפני
     ההחזרה, ולכן התשובה הראשונה הייתה הנוסח השני. בין נוסחים
     נרדפים זה לא הורגש; בסולם של `stuck` ו-`how` זה דילג על
     הצעד הראשון, שהוא בדיוק הצעד שהילד צריך. */
  var n = turn[id] || 0;
  turn[id] = (n + 1) % list.length;
  return list[n];
}

function norm(s) {
  return String(s || "").toLowerCase()
    .replace(/[׳״'"`.,!?;:()[\]{}]/g, " ")
    .replace(/\s+/g, " ").trim();
}

/* **גבול מילה, ולא תת־מחרוזת.** הניסוח הראשון חיפש `indexOf` פשוט,
   ו-"hi " נמצא בתוך "what is this" — כל שאלה באנגלית נפלה ל-"greet".
   נמדד ותוקן 14.9.2026. כאן כל ביטוי מוקף ברווחים משני הצדדים,
   ולכן "hi" תופס רק כשהוא מילה שלמה. */
function detect(text) {
  var whole = norm(text);
  var t = " " + whole + " ";
  for (var i = 0; i < INTENTS.length; i++) {
    var w = INTENTS[i].w, exact = INTENTS[i].x;
    for (var j = 0; j < w.length; j++) {
      var word = norm(w[j]);
      /* `x` — ההודעה כולה היא המילה, ולא מכילה אותה. ראו הנימוק
         שמעל `yes`/`no`: ״לא הבנתי״ אינו ״לא״. */
      if (exact ? whole === word : t.indexOf(" " + word + " ") >= 0) return INTENTS[i].id;
    }
  }
  return "none";
}

/* ---------------------------------------------------------------
   מצב הלומד גובר על הכוונה — אבל רק בשני מצבים.

   מי שהגלאי סימן `frustrated` ושואל ״מה זה״ אינו שואל על ההגדרה;
   הוא עייף. לכן `feel` קודם. `stuck` מקבל את נוסח ה-`stuck` גם
   אם הניסוח היה שאלה עניינית.

   `slow` **אינו** גובר: לאט אינו תקוע, ולומד איטי ששואל שאלה
   עניינית ראוי לתשובה עניינית.
   --------------------------------------------------------------- */
function byState(id, sign) {
  if (sign === "frustrated" && id !== "thanks" && id !== "bye") return "feel";
  if (sign === "stuck" && (id === "none" || id === "what" || id === "how")) return "stuck";
  return id;
}

